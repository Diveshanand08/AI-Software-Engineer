"""
pr_generator.py
Takes a code fix (e.g. from code_agent.py's self-correcting loop) and opens
a real pull request on GitHub: creates a branch + commits via git (subprocess),
pushes it, then opens a PR via the GitHub API.

Requires:
- GITHUB_TOKEN in .env with 'repo' scope
- Must be run from inside a local clone of the target repo (uses your existing
  git remote/credentials rather than re-authenticating over the API for git ops)

Usage:
    python pr_generator.py \
        --repo "Diveshanand08/AI-Software-Engineer" \
        --file "path/in/repo/example.py" \
        --fixed-code-file "local_fixed_version.py" \
        --title "Fix ZeroDivisionError in example.py" \
        --description "Adds error handling for division by zero."
"""

import argparse
import os
import subprocess
import time
import uuid
from pathlib import Path

from core.config import settings

GITHUB_TOKEN = settings.GITHUB_TOKEN


def run_git(args: list[str], cwd: str = "."):
    result = subprocess.run(["git"] + args, cwd=cwd, capture_output=True, text=True)
    if result.returncode != 0:
        raise RuntimeError(f"git {' '.join(args)} failed:\n{result.stderr}")
    return result.stdout.strip()


def create_fix_pr(
    repo_full_name: str,
    file_path_in_repo: str,
    new_content: str,
    pr_title: str,
    pr_description: str,
    base_branch: str = "main",
) -> str:
    if not GITHUB_TOKEN:
        raise RuntimeError("GITHUB_TOKEN not found in .env.")

    branch_name = f"auto-fix/{Path(file_path_in_repo).stem}-{uuid.uuid4().hex[:6]}"

    # 1. make sure we're up to date and on base branch
    run_git(["fetch", "origin"])
    run_git(["checkout", base_branch])
    run_git(["pull", "origin", base_branch])

    # 2. create new branch
    run_git(["checkout", "-b", branch_name])

    # 3. write the fixed file content
    target_path = Path(file_path_in_repo)
    target_path.parent.mkdir(parents=True, exist_ok=True)
    target_path.write_text(new_content, encoding="utf-8")

    # 4. commit
    run_git(["add", str(target_path)])
    run_git(["commit", "-m", f"Auto-fix: {pr_title}"])

    # 5. push the new branch
    run_git(["push", "-u", "origin", branch_name])

    # 6. switch back to base branch locally (cleanup)
    run_git(["checkout", base_branch])

    # 7. open the PR via GitHub API (with a short delay + retry to handle
    #    GitHub's eventual-consistency lag right after a fresh push)
    auth = Auth.Token(GITHUB_TOKEN)
    gh = Github(auth=auth)
    repo = gh.get_repo(repo_full_name)

    last_error = None
    for attempt in range(1, 4):
        time.sleep(3)  # give GitHub a moment to register the new branch/push
        try:
            pr = repo.create_pull(
                title=pr_title,
                body=pr_description,
                head=branch_name,
                base=base_branch,
            )
            return pr.html_url
        except Exception as e:
            last_error = e
            print(f"[pr_generator] create_pull attempt {attempt} failed, retrying...")

    raise RuntimeError(f"could not create PR after 3 attempts. last error :{last_error}"
                       f"The branch '{branch_name}' was pushed successfully - you can open the PR manually on GitHub if this keeps failing."
    )


def main():
    parser = argparse.ArgumentParser(description="Open a GitHub PR with a code fix.")
    parser.add_argument("--repo", required=True, help="owner/repo, e.g. Diveshanand08/AI-Software-Engineer")
    parser.add_argument("--file", required=True, help="Path to the file INSIDE the local repo (e.g. src/utils.py)")
    parser.add_argument("--fixed-code-file", required=True, help="Local path to the fixed code content")
    parser.add_argument("--title", required=True, help="PR title")
    parser.add_argument("--description", default="Automated fix generated by the self-correcting code agent.", help="PR description")
    parser.add_argument("--base", default="main", help="Base branch to PR against")
    args = parser.parse_args()

    new_content = Path(args.fixed_code_file).read_text(encoding="utf-8")

    print(f"[pr_generator] Creating PR against {args.repo}:{args.base} ...")
    pr_url = create_fix_pr(
        repo_full_name=args.repo,
        file_path_in_repo=args.file,
        new_content=new_content,
        pr_title=args.title,
        pr_description=args.description,
        base_branch=args.base,
    )
    print(f"[pr_generator] Pull request opened: {pr_url}")


if __name__ == "__main__":
    main()