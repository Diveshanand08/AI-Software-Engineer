import { useEffect, useState, useCallback, useRef } from 'react'
import { GoogleLogin } from '@react-oauth/google'
import { Command, GitBranch, Settings2, Menu, LogOut, Plus, ExternalLink, X, Loader2 } from 'lucide-react'
import { Sidebar } from './components/codeassist/Sidebar.jsx'
import { ChatPanel } from './components/codeassist/ChatPanel.jsx'
import { CommandInput } from './components/codeassist/CommandInput.jsx'
import { ModelPicker } from './components/codeassist/ModelPicker.jsx'
import { useAuth } from './lib/useAuth.js'
const API_BASE = import.meta.env.VITE_API_BASE || 'http://localhost:8000'
const MODE_TITLE = {
  chat: 'Chat',
  explain: 'Explain',
  bugs: 'Find Bugs',
  agent: 'Auto-Coder Agent',
  tests: 'Generate Unit Tests'
}

export default function App() {
  const { user, displayName, login, logout } = useAuth()
  const [mode, setMode] = useState('chat')
  const [collection, setCollection] = useState('test_repo')
  
  // Sidebar state
  const [isSidebarOpen, setIsSidebarOpen] = useState(false)

  const [activeSessionId, setActiveSessionId] = useState(null)
  const skipSessionLoadRef = useRef(false)
  const [messages, setMessages] = useState([])
  const [historyList, setHistoryList] = useState([]) 

  const [input, setInput] = useState('')
  const [loading, setLoading] = useState(false)
  const [elapsed, setElapsed] = useState(0)
  const [status, setStatus] = useState({ ok: false })
  const [repoUrl, setRepoUrl] = useState('')
  const [isIndexing, setIsIndexing] = useState(false)
  const [provider, setProvider] = useState(() => localStorage.getItem('provider') || 'ollama')
  const [availableCollections, setAvailableCollections] = useState(['test_repo'])

  const fetchCollections = useCallback(async () => {
    try {
      const res = await fetch(`${API_BASE}/collections`)
      if (res.ok) {
        const data = await res.json()
        if (Array.isArray(data) && data.length > 0) {
          setAvailableCollections(data)
        }
      }
    } catch {}
  }, [])

  useEffect(() => {
    fetchCollections()
  }, [fetchCollections])

function handleProviderChange(p) {
  setProvider(p)
  localStorage.setItem('provider', p)
}

  // Pull Request Modal states
  const [isPrModalOpen, setIsPrModalOpen] = useState(false)
  const [prRepo, setPrRepo] = useState('Diveshanand08/AI-Software-Engineer')
  const [prFile, setPrFile] = useState('test_fix_content.py')
  const [prTitle, setPrTitle] = useState('Auto-fix: resolve issue in code')
  const [prDesc, setPrDesc] = useState('Automated fix generated by AI Code Assistant.')
  const [prContent, setPrContent] = useState('# Automated fix generated by CodeAssist\n\ndef add(a, b):\n    return a + b\n')
  const [isCreatingPr, setIsCreatingPr] = useState(false)
  const [prResult, setPrResult] = useState(null)
  const [prError, setPrError] = useState(null)

  async function handleCreatePR(e) {
    e.preventDefault()
    setIsCreatingPr(true)
    setPrError(null)
    setPrResult(null)
    try {
      const res = await fetch(`${API_BASE}/pr`, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          repo: prRepo,
          file_path: prFile,
          new_content: prContent,
          title: prTitle,
          description: prDesc,
        }),
      })
      if (!res.ok) {
        const errText = await res.text()
        throw new Error(errText || 'Failed to create PR')
      }
      const data = await res.json()
      setPrResult(data)
    } catch (err) {
      setPrError(err.message)
    } finally {
      setIsCreatingPr(false)
    }
  }

  const fetchHistory = useCallback(async () => {
    try {
      const emailQuery = user?.email ? `?user_email=${encodeURIComponent(user.email)}` : ''
      const res = await fetch(`${API_BASE}/sessions${emailQuery}`)
      if (res.ok) {
        const data = await res.json()
        setHistoryList(data)
      }
    } catch (e) {
      console.error("Failed to fetch history:", e)
    }
  }, [user?.email])

  useEffect(() => {
    setActiveSessionId(null)
    setMessages([])
    fetchHistory()
  }, [user?.email, fetchHistory])

  useEffect(() => {
    fetch(`${API_BASE}/`)
      .then((res) => setStatus({ ok: res.ok }))
      .catch(() => setStatus({ ok: false }))
  }, [])

  useEffect(() => {
    if (skipSessionLoadRef.current) {
      skipSessionLoadRef.current = false
      return
    }
    if (!activeSessionId) {
      setMessages([]) 
      return
    }
    const loadPastChat = async () => {
      try {
        const res = await fetch(`${API_BASE}/sessions/${activeSessionId}`)
        if (res.ok) {
          const data = await res.json()
          const formatted = data.map(m => ({ ...m, id: crypto.randomUUID() }))
          setMessages(formatted)
        }
      } catch (e) {
        console.error("Failed to load session:", e)
      }
    }
    loadPastChat()
  }, [activeSessionId])

  useEffect(() => {
    let timer
    if (loading) {
      setElapsed(0)
      timer = setInterval(() => setElapsed((e) => e + 1), 1000)
    }
    return () => clearInterval(timer)
  }, [loading])

  const [indexStatusMsg, setIndexStatusMsg] = useState('')
  const pollTimerRef = useRef(null)

  function cancelIndexing() {
    if (pollTimerRef.current) clearInterval(pollTimerRef.current)
    setIsIndexing(false)
    setIndexStatusMsg('')
  }

  function appendMessage(m) {
    setMessages((prev) => [...prev, m])
  }

  async function handleImport() {
    const trimmedUrl = repoUrl.trim()
    const targetColl = collection.trim().replace(/\s+/g, '_')
    if (!trimmedUrl || !targetColl || isIndexing) return

    if (trimmedUrl.startsWith('https://github.com/')) {
      const parts = trimmedUrl.replace('https://github.com/', '').replace(/\.git$/, '').split('/').filter(Boolean)
      if (parts.length < 2) {
        alert("⚠️ Please provide a complete GitHub repository URL, for example:\nhttps://github.com/username/repository")
        return
      }
    }

    setIsIndexing(true)
    setIndexStatusMsg('Sending index request to server...')
    if (pollTimerRef.current) clearInterval(pollTimerRef.current)

    try {
      const res = await fetch(`${API_BASE}/index`, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ name: targetColl, repo_url: trimmedUrl }),
      })
      if (!res.ok) {
        const errText = await res.text()
        throw new Error(errText || 'Failed to start indexing')
      }
      
      setIndexStatusMsg(`Cloning repository into ${targetColl}...`)

      // Poll indexing status every 2.5s until completed or failed
      let attempts = 0
      let unknownAttempts = 0
      pollTimerRef.current = setInterval(async () => {
        attempts++
        try {
          const statusRes = await fetch(`${API_BASE}/index/status/${encodeURIComponent(targetColl)}`)
          if (statusRes.ok) {
            const data = await statusRes.json()
            if (data.status === 'in_progress') {
              if (data.message) setIndexStatusMsg(data.message)
            } else if (data.status === 'completed') {
              clearInterval(pollTimerRef.current)
              setIsIndexing(false)
              setIndexStatusMsg('')
              setRepoUrl('')
              setCollection(targetColl)
              fetchCollections()
              alert(`🎉 Successfully indexed '${targetColl}'! You can now chat and ask questions about this codebase.`)
            } else if (data.status === 'failed') {
              clearInterval(pollTimerRef.current)
              setIsIndexing(false)
              setIndexStatusMsg('')
              alert(`❌ Indexing failed for '${targetColl}': ${data.error || 'Unknown error'}`)
            } else if (data.status === 'unknown') {
              unknownAttempts++
              if (unknownAttempts >= 5) {
                clearInterval(pollTimerRef.current)
                setIsIndexing(false)
                setIndexStatusMsg('')
                alert(`⚠️ Indexing process was interrupted or server restarted. Please click Clone & Index again.`)
              }
            }
          }
        } catch {
          // ignore transient poll network blips
        }
        if (attempts >= 80) { // 200 seconds timeout
          clearInterval(pollTimerRef.current)
          setIsIndexing(false)
          setIndexStatusMsg('')
          alert(`⚠️ Indexing is taking longer than expected. Please check your backend terminal.`)
        }
      }, 2500)
    } catch (e) {
      alert(`Error starting import: ${e.message}`)
      setIsIndexing(false)
      setIndexStatusMsg('')
    }
  }

  async function handleDeleteSession(id) {
    try {
      await fetch(`${API_BASE}/sessions/${id}`, { method: 'DELETE' })
      if (activeSessionId === id) {
        setActiveSessionId(null)
        setMessages([])
      }
      fetchHistory()
    } catch (e) {
      console.error('Failed to delete session:', e)
    }
  }

  async function send(text) {
    const trimmed = text.trim()
    if (!trimmed || loading) return

    appendMessage({ id: crypto.randomUUID(), role: 'user', content: trimmed })
    setInput('')
    setLoading(true)


    try {
      if (mode === 'bugs') {
        const res = await fetch(`${API_BASE}/bugs`, {
          method: 'POST',
          headers: { 'Content-Type': 'application/json' },
          body: JSON.stringify({ file_path: trimmed }),
        })
        const data = await res.json()
        appendMessage({ id: crypto.randomUUID(), role: 'assistant', content: data.analysis || 'No response.' })
      } else if (mode === 'agent') {
        const res = await fetch(`${API_BASE}/agent`, {
          method: 'POST',
          headers: { 'Content-Type': 'application/json' },
          body: JSON.stringify({
            task: trimmed,
            session_id: activeSessionId,
            user_email: user?.email || '',
            model: 'phi3',
          }),
        })
        const data = await res.json()
        if (data.session_id) {
          setActiveSessionId(data.session_id)
          fetchHistory()
        }
        const statusBadge = data.success
          ? `✅ **Auto-Coder Solved Task!** (in ${data.attempts} attempt${data.attempts > 1 ? 's' : ''})`
          : `❌ **Auto-Coder Failed** (${data.attempts} attempts reached)`
        const content = `${statusBadge}\n\n\`\`\`python\n${data.code}\n\`\`\`\n\n**Docker Sandbox Execution Output:**\n\`\`\`\n${data.stdout || data.stderr || data.error || 'No output.'}\n\`\`\``
        appendMessage({ id: crypto.randomUUID(), role: 'assistant', content })
      } else if (mode === 'tests') {
        const res = await fetch(`${API_BASE}/tests`, {
          method: 'POST',
          headers: { 'Content-Type': 'application/json' },
          body: JSON.stringify({
            collection,
            target: trimmed,
            session_id: activeSessionId,
            user_email: user?.email || '',
            model: 'phi3',
          }),
        })
        const data = await res.json()
        if (data.session_id) {
          setActiveSessionId(data.session_id)
          fetchHistory()
        }
        const statusBadge = data.success
          ? `✅ **Unit Tests Passed in Docker!** (${data.attempts} attempt${data.attempts > 1 ? 's' : ''})`
          : `⚠️ **Tests Failed in Docker Sandbox**`
        const content = `${statusBadge}\n\n\`\`\`python\n${data.code}\n\`\`\`\n\n**Test Runner Output:**\n\`\`\`\n${data.stdout || data.error || 'No output.'}\n\`\`\``
        appendMessage({ id: crypto.randomUUID(), role: 'assistant', content })
      } else {
        const endpoint = mode === 'explain' ? '/explain' : '/ask'
        const body = {
          collection,
          question: trimmed,
          target: trimmed,
          session_id: activeSessionId,
          provider,
          user_email: user?.email || '',
        }
        
        const res = await fetch(`${API_BASE}${endpoint}`, {
          method: 'POST',
          headers: { 'Content-Type': 'application/json' },
          body: JSON.stringify(body),
        })

        if (!res.ok) {
          const errText = await res.text()
          throw new Error(errText || `Server error: ${res.status}`)
        }

        const msgId = crypto.randomUUID()
        appendMessage({ id: msgId, role: 'assistant', content: '' })

        const reader = res.body.getReader()
        const decoder = new TextDecoder()
        let buffer = ''
        
        while (true) {
          const { done, value } = await reader.read()
          if (done) break
          
          buffer += decoder.decode(value, { stream: true })
          
          const sessionMatch = buffer.match(/__SESSION_ID__:(.+?)\n\n/)
          if (sessionMatch) {
            skipSessionLoadRef.current = true
            setActiveSessionId(sessionMatch[1])
            buffer = buffer.replace(sessionMatch[0], '')
            fetchHistory() 
          }

          if (buffer.includes('__SESSION_ID') && !sessionMatch) {
            continue 
          }
          
          if (buffer.length > 0) {
            const currentText = buffer
            setMessages(prev => prev.map(msg => 
              msg.id === msgId ? { ...msg, content: msg.content + currentText } : msg
            ))
            buffer = '' 
          }
        }
      }
    } catch (e) {
      appendMessage({ id: crypto.randomUUID(), role: 'assistant', content: `Error: ${e.message}` })
    } finally {
      setLoading(false)
    }
  }

  const handleNewChat = useCallback(() => {
    setActiveSessionId(null)
    setMessages([])
    setIsSidebarOpen(false)
  }, [])

  return (
    <div className="bg-grid fixed inset-0 flex overflow-hidden bg-background">
      <div className="glow-amber pointer-events-none absolute -left-40 -top-40 h-96 w-96 rounded-full blur-3xl" />
      <div className="glow-amber pointer-events-none absolute -bottom-40 right-10 h-96 w-96 rounded-full opacity-60 blur-3xl" />

      {/* Floating Sidebar Overlay */}
      <Sidebar
        isOpen={isSidebarOpen}
        onClose={() => setIsSidebarOpen(false)}
        mode={mode}
        onModeChange={setMode}
        collection={collection}
        onCollectionChange={setCollection}
        status={status}
        repoUrl={repoUrl}
        onRepoUrlChange={setRepoUrl}
        onImport={handleImport}
        isIndexing={isIndexing}
        indexStatusMsg={indexStatusMsg}
        onCancelIndex={cancelIndexing}
        apiBase={API_BASE}
        historyList={historyList}
        activeSessionId={activeSessionId}
        onSelectSession={(id) => {
          setActiveSessionId(id)
          setIsSidebarOpen(false)
        }}
        onNewChat={handleNewChat}
        onDeleteSession={handleDeleteSession}
      />

      {/* Ensure the main container does NOT scroll by adding relative, h-full, and overflow-hidden */}
      <main className="relative z-10 flex h-full min-w-0 flex-1 flex-col overflow-hidden">
        
        {/* Header - Stays fixed at top */}
        <header className="glass shrink-0 flex items-center justify-between border-b px-4 py-3 md:px-8">
          <div className="flex items-center gap-3">
            <button 
              onClick={() => setIsSidebarOpen(true)}
              className="mr-2 flex h-8 w-8 items-center justify-center rounded-lg hover:bg-white/10 text-gray-400 hover:text-white transition-colors"
            >
              <Menu className="h-5 w-5" />
            </button>
            <h1 className="font-mono text-sm font-semibold tracking-tight text-foreground">
              {MODE_TITLE[mode]}
            </h1>
            <div className="hidden sm:flex items-center gap-1 rounded-lg border border-border bg-secondary/50 px-2 py-1 font-mono text-xs text-muted-foreground">
              <span className="text-blue-400">#</span>
              <select
                value={collection}
                onChange={(e) => setCollection(e.target.value)}
                className="bg-transparent text-gray-200 outline-none cursor-pointer text-xs font-mono pr-1"
                title="Select indexed repository collection"
              >
                {Array.from(new Set([collection, ...availableCollections])).map((c) => (
                  <option key={c} value={c} className="bg-[#1e1f20] text-gray-200">
                    {c}
                  </option>
                ))}
              </select>
            </div>

            <button
              onClick={handleNewChat}
              className="flex items-center gap-1.5 rounded-lg border border-border bg-secondary/40 px-2.5 py-1 font-mono text-xs text-muted-foreground transition-colors hover:bg-secondary/70 hover:text-foreground active:scale-95"
              title="Start a new chat"
            >
              <Plus className="h-3.5 w-3.5 text-blue-400" />
              <span className="hidden sm:inline">New Chat</span>
            </button>
          </div>
          <div className="flex items-center gap-1.5">
            <ModelPicker apiBase={API_BASE} value={provider} onChange={handleProviderChange} />
  
            <button
              type="button"
              onClick={() => setIsPrModalOpen(true)}
              aria-label="Create Pull Request"
              title="Create Pull Request on GitHub"
              className="flex items-center gap-1.5 rounded-lg border border-border bg-secondary/40 px-2.5 py-1 text-xs font-mono text-muted-foreground transition-colors hover:bg-secondary/70 hover:text-foreground active:scale-95"
            >
              <GitBranch className="h-3.5 w-3.5 text-emerald-400" />
              <span className="hidden sm:inline">Open PR</span>
            </button>
            <button type="button" aria-label="Settings" className="flex h-8 w-8 items-center justify-center rounded-lg border border-border bg-secondary/40 text-muted-foreground transition-colors hover:text-foreground">
              <Settings2 className="h-4 w-4" />
            </button>

            {/* Auth section */}
            {user ? (
              <div className="flex items-center gap-2 ml-1">
                {user.picture ? (
                  <img src={user.picture} alt={displayName} className="h-7 w-7 rounded-full ring-1 ring-white/20" />
                ) : (
                  <div className="flex h-7 w-7 items-center justify-center rounded-full bg-blue-600 font-mono text-xs font-bold text-white">
                    {displayName[0].toUpperCase()}
                  </div>
                )}
                <button
                  onClick={logout}
                  title="Sign out"
                  className="flex h-7 w-7 items-center justify-center rounded-lg text-gray-500 hover:bg-white/10 hover:text-white transition-colors"
                >
                  <LogOut className="h-3.5 w-3.5" />
                </button>
              </div>
            ) : (
              <div className="ml-1 scale-75 origin-right">
                <GoogleLogin
                  onSuccess={login}
                  onError={() => console.error('Google login failed')}
                  shape="pill"
                  size="medium"
                  theme="filled_black"
                  text="signin"
                />
              </div>
            )}
          </div>
        </header>

        {/* 
          THE FIX: 
          We separate the ChatPanel and the CommandInput completely.
          ChatPanel takes up all available vertical space (flex-1).
          CommandInput is absolutely positioned relative to this specific wrapper. 
        */}
        <div className="relative flex-1 overflow-hidden">
          
          {/* Chat Container - Scrolls independently */}
          <div className="absolute inset-0 z-0">
            <ChatPanel
              messages={messages}
              mode={mode}
              onExample={send}
              loading={loading}
              elapsed={elapsed}
              displayName={displayName}
              historyList={historyList}
              onSelectSession={(id) => setActiveSessionId(id)}
            />
          </div>

          {/* 
            Floating Search Bar - Locked to the bottom.
            pointer-events-none lets you click "through" the gradient to interact with the chat below.
          */}
          <div className="pointer-events-none absolute bottom-0 left-0 z-20 w-full bg-linear-to-t from-[#0d1117] via-[#0d1117]/90 to-transparent pb-6 pt-16">
            <div className="pointer-events-auto">
              <CommandInput value={input} onChange={setInput} onSubmit={() => send(input)} mode={mode} disabled={loading} />
            </div>
          </div>

        </div>
      </main>

      {/* GitHub Pull Request Modal */}
      {isPrModalOpen && (
        <div className="fixed inset-0 z-50 flex items-center justify-center bg-black/60 backdrop-blur-sm p-4">
          <div className="relative w-full max-w-lg rounded-2xl border border-white/10 bg-[#161b22] p-6 shadow-2xl space-y-4">
            <div className="flex items-center justify-between border-b border-white/10 pb-3">
              <div className="flex items-center gap-2">
                <span className="flex h-7 w-7 items-center justify-center rounded-lg bg-emerald-500/20 text-emerald-400">
                  <GitBranch className="h-4 w-4" />
                </span>
                <h2 className="text-base font-semibold text-white">Create GitHub Pull Request</h2>
              </div>
              <button
                onClick={() => { setIsPrModalOpen(false); setPrResult(null); setPrError(null) }}
                className="rounded-lg p-1 text-gray-400 hover:bg-white/10 hover:text-white"
              >
                <X className="h-4 w-4" />
              </button>
            </div>

            {prResult ? (
              <div className="rounded-xl border border-emerald-500/30 bg-emerald-500/10 p-4 text-emerald-300 space-y-3">
                <p className="font-semibold text-sm">🎉 {prResult.message}</p>
                <a
                  href={prResult.pr_url}
                  target="_blank"
                  rel="noreferrer"
                  className="inline-flex items-center gap-1.5 rounded-lg bg-emerald-500 px-3 py-1.5 text-xs font-bold text-black hover:bg-emerald-400 transition-colors"
                >
                  View Pull Request on GitHub <ExternalLink className="h-3 w-3" />
                </a>
              </div>
            ) : (
              <form onSubmit={handleCreatePR} className="space-y-3 text-xs">
                {prError && (
                  <div className="rounded-lg border border-rose-500/30 bg-rose-500/10 p-2.5 text-rose-300">
                    {prError}
                  </div>
                )}
                <div>
                  <label className="block mb-1 text-gray-400 font-medium">GitHub Repository</label>
                  <input
                    type="text"
                    value={prRepo}
                    onChange={(e) => setPrRepo(e.target.value)}
                    required
                    placeholder="owner/repo"
                    className="w-full rounded-lg border border-white/10 bg-[#0d1117] px-3 py-2 font-mono text-gray-200 focus:outline-none focus:ring-1 focus:ring-emerald-500"
                  />
                </div>
                <div>
                  <label className="block mb-1 text-gray-400 font-medium">File Path in Repo</label>
                  <input
                    type="text"
                    value={prFile}
                    onChange={(e) => setPrFile(e.target.value)}
                    required
                    placeholder="e.g. test_fix_content.py"
                    className="w-full rounded-lg border border-white/10 bg-[#0d1117] px-3 py-2 font-mono text-gray-200 focus:outline-none focus:ring-1 focus:ring-emerald-500"
                  />
                </div>
                <div>
                  <label className="block mb-1 text-gray-400 font-medium">PR Title</label>
                  <input
                    type="text"
                    value={prTitle}
                    onChange={(e) => setPrTitle(e.target.value)}
                    required
                    className="w-full rounded-lg border border-white/10 bg-[#0d1117] px-3 py-2 text-gray-200 focus:outline-none focus:ring-1 focus:ring-emerald-500"
                  />
                </div>
                <div>
                  <label className="block mb-1 text-gray-400 font-medium">Code Content</label>
                  <textarea
                    rows={5}
                    value={prContent}
                    onChange={(e) => setPrContent(e.target.value)}
                    required
                    className="w-full rounded-lg border border-white/10 bg-[#0d1117] px-3 py-2 font-mono text-gray-200 focus:outline-none focus:ring-1 focus:ring-emerald-500"
                  />
                </div>
                <div className="flex justify-end gap-2 pt-2">
                  <button
                    type="button"
                    onClick={() => setIsPrModalOpen(false)}
                    className="rounded-lg border border-white/10 px-3 py-2 text-gray-400 hover:bg-white/5"
                  >
                    Cancel
                  </button>
                  <button
                    type="submit"
                    disabled={isCreatingPr}
                    className="flex items-center gap-1.5 rounded-lg bg-emerald-600 px-4 py-2 font-semibold text-white hover:bg-emerald-500 disabled:opacity-50"
                  >
                    {isCreatingPr ? <Loader2 className="h-3.5 w-3.5 animate-spin" /> : null}
                    {isCreatingPr ? 'Pushing & Opening PR...' : 'Create PR'}
                  </button>
                </div>
              </form>
            )}
          </div>
        </div>
      )}
    </div>
  )
}